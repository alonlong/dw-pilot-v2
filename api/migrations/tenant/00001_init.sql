-- 工地。
create table job (
    id      text primary key check (id <> ''),
    name    text not null,
    address text not null default ''
);

-- 日报：同一工地同一业务日期只有一份。
create table report (
    id            bigint generated by default as identity primary key,
    job_id        text not null references job (id),
    business_date date not null,
    submitted_at  timestamptz,
    locked        boolean not null default false,
    created_at    timestamptz not null default now(),
    unique (job_id, business_date)
);

-- 工人工时。
create table crew_hours (
    report_id bigint not null references report (id) on delete cascade,
    worker    text not null check (worker <> ''),
    hours     double precision not null check (hours >= 0),
    primary key (report_id, worker)
);

-- 追加的备注，按 id 保序。author_id 是 public.app_user 的 id，但不建外键：跨 schema 的外键
-- 会让建删租户 schema 时锁住 public.app_user、删用户时扫描每个租户的 report_note，
-- 并发重建槽位会互相死锁。author_name 记下写入时的作者名（快照里的备注没有对应的用户）。
create table report_note (
    id          bigint generated by default as identity primary key,
    report_id   bigint not null references report (id) on delete cascade,
    body        text not null check (char_length(body) between 1 and 500),
    author_id   bigint,
    author_name text not null,
    created_at  timestamptz not null default now()
);

create index report_note_report_idx on report_note (report_id, id);

